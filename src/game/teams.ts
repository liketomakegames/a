export function normalizeTeamCode(code: string): string {
  const cleaned = code.replace(/[^a-zA-Z0-9]/g, '').toUpperCase().slice(0, 3);
  return cleaned.length > 0 ? cleaned.padEnd(3, 'X').slice(0, 3) : 'TEA';
}

export function updateTeamKit(
  team: TeamConfig,
  patch: Partial<Pick<TeamConfig, 'name' | 'code' | 'primaryColor' | 'secondaryColor' | 'gkColor'>>,
): TeamConfig {
  return {
    ...team,
    name: patch.name !== undefined ? patch.name.trim().slice(0, 22) || team.name : team.name,
    code: patch.code !== undefined ? normalizeTeamCode(patch.code) : team.code,
    primaryColor: patch.primaryColor ?? team.primaryColor,
    secondaryColor: patch.secondaryColor ?? team.secondaryColor,
    gkColor: patch.gkColor ?? team.gkColor,
  };
}
